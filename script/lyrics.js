const lyricsElement = document.querySelector("#lyrics");
const audio = document.querySelector("#music");

if (lyricsElement && audio) {

    let currentLyric = -1;
    let animationFrame = null;

    function updateLyrics() {
        const time = audio.currentTime;

        let newLyric = -1;

        for (let i = 0; i < lyricsTimeline.length; i++) {
            if (time >= lyricsTimeline[i][0]) {
                newLyric = i;
            } else {
                break;
            }
        }

        if (newLyric === currentLyric) return;

        currentLyric = newLyric;

        const text =
            newLyric >= 0
                ? lyricsTimeline[newLyric][1]
                : "";

                lyricsElement.textContent = text;

                lyricsElement.classList.toggle(
                    "is-visible",
                    text !== ""
                );
                
                // Alternar posición entre izquierda y derecha
                lyricsElement.classList.remove("is-right");
                
                if (newLyric >= 0 && newLyric % 2 !== 0) {
                    lyricsElement.classList.add("is-right");
                }
    }


    function syncLyrics() {
        if (!audio.paused && !audio.ended) {
            updateLyrics();
            animationFrame = requestAnimationFrame(syncLyrics);
        }
    }


    audio.addEventListener("play", () => {
        updateLyrics();

        cancelAnimationFrame(animationFrame);
        animationFrame = requestAnimationFrame(syncLyrics);
    });


    audio.addEventListener("pause", () => {
        cancelAnimationFrame(animationFrame);
    });


    audio.addEventListener("ended", () => {
        cancelAnimationFrame(animationFrame);

        currentLyric = -1;
        lyricsElement.textContent = "";
        lyricsElement.classList.remove("is-visible");
    });


    audio.addEventListener("seeking", updateLyrics);


    window.addEventListener("pageshow", () => {
        currentLyric = -1;

        lyricsElement.textContent = "";
        lyricsElement.classList.remove("is-visible");

        updateLyrics();
    });


    updateLyrics();
}